void circle_width3(uint16_t x,uint16_t y,uint16_t r,uint16_t color){
    if(r<3){return;}
    int r_out=r,r_in=r-3;
    int xr_out=r_out,xr_in=r_in;
    int sq_out=r_out*r_out,sq_in=r_in*r_in;
    for(int i=0;i<=r_out;i++){
        while((i*i+xr_out*xr_out)>sq_out){xr_out--;}
        if(i<=r_in){
            while((i*i+xr_in*xr_in)>sq_in){xr_in--;}
        }
        else{
            xr_in=-1;
        }
        int left_out  = x-xr_out;
        int right_out = x+xr_out;
        int left_in   = x-xr_in;
        int right_in  = x+xr_in;
        if(xr_in>=0){
            Lcd_draw_line(left_out,y+i,left_in-left_out,0,color);
            Lcd_draw_line(right_in,y+i,right_out-right_in,0,color);
        }
        else{
            Lcd_draw_line(left_out,y+i,right_out-left_out,0,color);
        }
        if(i!=0){
            if(xr_in>=0){
                Lcd_draw_line(left_out,y-i,left_in-left_out,0,color);
                Lcd_draw_line(right_in,y-i,right_out-right_in,0,color);
            }
            else{
                Lcd_draw_line(left_out,y-i,right_out-left_out,0,color);
            }
        }
    }
}
